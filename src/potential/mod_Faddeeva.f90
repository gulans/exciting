  !> @brief Helper function to compute Im[w(x)] for real x.
  PURE FUNCTION w_im(x_in) RESULT(res)
    REAL(real64), INTENT(IN) :: x_in
    REAL(real64)             :: res
    IF (x_in >= 0) THEN
       IF (x_in > 45) THEN
          IF (x_in > 5e7_real64) THEN
              res = ISPI / x_in
          ELSE
              res = ISPI*((x_in*x_in) * (x_in*x_in-4.5_real64) + 2.0_real64) / (x_in * ((x_in*x_in) * (x_in*x_in-5.0_real64) + 3.75_real64))
          END IF
       ELSE
          res = w_im_helper(100.0_real64 / (1.0_real64 + x_in), x_in)
       END IF
    ELSE
       IF (x_in < -45) THEN
          IF (x_in < -5e7_real64) THEN
              res = ISPI / x_in
          ELSE
              res = ISPI*((x_in*x_in) * (x_in*x_in-4.5_real64) + 2.0_real64) / (x_in * ((x_in*x_in) * (x_in*x_in-5.0_real64) + 3.75_real64))
          END IF
       ELSE
          res = -w_im_helper(100.0_real64 / (1.0_real64 - x_in), -x_in)
       END IF
    END IF
  END FUNCTION w_im

  PURE FUNCTION sinh_taylor(x) RESULT(res)
      REAL(real64), INTENT(IN) :: x
      REAL(real64) :: res
      res = x * (1.0_real64 + (x*x) * (0.16666666666666666667_real64 &
               + 0.0083333333333333333333_real64 * (x*x)))
  END FUNCTION sinh_taylor

  PURE FUNCTION sinc(x, sinx) RESULT(res)
      REAL(real64), INTENT(IN) :: x, sinx
      REAL(real64) :: res
      IF (ABS(x) < 1.0e-4_real64) THEN
          res = 1.0_real64 - (0.16666666666666666667_real64)*x*x
      ELSE
          res = sinx / x
      END IF
  END FUNCTION sinc

  !> @brief Computes the Faddeeva function w(z) = exp(-z^2)erfc(-iz).
  !> @param z Complex input value.
  !> @param relerr Desired relative error.
  !> @return The complex value of w(z).
  RECURSIVE FUNCTION Faddeeva_w(z, relerr_in) RESULT(ret)
    COMPLEX(real64), INTENT(IN) :: z
    REAL(real64), INTENT(IN)    :: relerr_in
    COMPLEX(real64)             :: ret

    REAL(real64) :: x, y, ya, a, a2, c, relerr
    REAL(real64) :: sum1, sum2, sum3, sum4, sum5
    REAL(real64) :: sum4_c, sum5_c  ! compensators for Kahan
    real(kind=real64) :: v, yk, t   ! temporaries for compensators
    REAL(real64) :: xs, dr, di, denom, nu, wr, wi, nu_start, n0
    REAL(real64) :: prod2ax, prodm2ax, expx2, exp2ax, expm2ax, coef, dx, exp1, exp1dn, np, nm, tp, tm, yax, xya
    INTEGER      :: n, dn
    REAL(real64), PARAMETER :: c0=3.9_real64, c1=11.398_real64, c2=0.08254_real64, c3=0.1421_real64, c4=0.2023_real64
    COMPLEX(real64) :: exp_term
    REAL(real64)    :: sinxy, cos2xy, sin2xy, coef1, coef2, expx2erfcxy, exp_arg_re

    ! FOR DEBUG
    complex(real64) :: tmp

    relerr = relerr_in

    IF (AIMAG(z) < 0.0_real64) THEN
      ! Evaluate w at the conjugate (Im >= 0) and use the identity:
      !   w(z) = 2*exp(-z^2) - conj( w(conjg(z)) )
      ! We call the same function recursively on conjg(z); because conjg(z)
      ! has non-negative imaginary part the recursion will not loop.
      tmp = Faddeeva_w(CONJG(z), relerr_in)
      ret = 2.0_real64 * EXP(-z*z) - CONJG(tmp)
      RETURN
    END IF
    

    x = REAL(z, kind=real64)
    y = AIMAG(z)

    IF (x == 0.0_real64) THEN
      ret = CMPLX(erfcx_real(y), x, kind=real64)
      RETURN
    ELSE IF (y == 0.0_real64) THEN
      ret = CMPLX(EXP(-x*x), w_im(x), kind=real64)
      RETURN
    END IF

    IF (relerr <= EPSILON(0.0_real64)) THEN
      relerr = EPSILON(0.0_real64)
      a  = 0.518321480430085929872_real64
      c  = 0.329973702884629072537_real64
      a2 = 0.268657157075235951582_real64
    ELSE
      IF (relerr > 0.1_real64) relerr = 0.1_real64
      a = PI / SQRT(-LOG(relerr * 0.5_real64))
      c = (2.0_real64 / PI) * a
      a2 = a*a
    END IF

    x = ABS(REAL(z, kind=real64))
    ya = ABS(y)

    ret = (0.0_real64, 0.0_real64)
    sum1 = 0.0_real64; sum2 = 0.0_real64; sum3 = 0.0_real64
    sum4 = 0.0_real64; sum5 = 0.0_real64
    sum4_c = 0.0_real64; sum5_c = 0.0_real64

    ! Continued fraction for large |z|
    IF (ya > 7.0_real64 .OR. (x > 6.0_real64 .AND. (ya > 0.1_real64 .OR. &
        (x > 8.0_real64 .AND. ya > 1.0e-10_real64) .OR. x > 28.0_real64))) THEN

      IF (y < 0.0_real64) THEN
          xs = -REAL(z, kind=real64)
      ELSE
          xs = REAL(z, kind=real64)
      END IF

      IF (x + ya > 4000.0_real64) THEN
        IF (x + ya > 1.0e7_real64) THEN
          IF (.NOT. ieee_is_finite(ya)) THEN
              IF (ieee_is_nan(x) .OR. y < 0.0_real64) THEN
                  ret = CMPLX(HUGE(0.0_real64)/HUGE(0.0_real64), HUGE(0.0_real64)/HUGE(0.0_real64), kind=real64) ! NaN
              ELSE
                  ret = CMPLX(0.0_real64, 0.0_real64, kind=real64)
              END IF
              RETURN
          END IF
          IF (x > ya) THEN
            yax = ya / xs
            denom = ISPI / (xs + yax*ya)
            ret = CMPLX(denom*yax, denom, kind=real64)
          ELSE
            xya = xs / ya
            denom = ISPI / (xya*xs + ya)
            ret = CMPLX(denom, denom*xya, kind=real64)
          END IF
        ELSE
          dr = xs*xs - ya*ya - 0.5_real64
          di = 2.0_real64 * xs * ya
          denom = ISPI / (dr*dr + di*di)
          ret = CMPLX(denom * (xs*di-ya*dr), denom * (xs*dr+ya*di), kind=real64)
        END IF
      ELSE
        nu_start = 0.5_real64 * (FLOOR(c0 + c1 / (c2*x + c3*ya + c4)) - 1.0_real64)
        wr = xs
        wi = ya
        DO nu = nu_start, 0.5_real64, -0.5_real64
          denom = nu / (wr*wr + wi*wi)
          wr = xs - wr * denom
          wi = ya + wi * denom
        END DO
