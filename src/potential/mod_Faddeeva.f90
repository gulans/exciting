         exp_arg_re = (ya-xs)*(xs+ya)
         IF (exp_arg_re > LOG(HUGE(0.0_real64)/2.0_real64)) THEN
            ! Construct Inf if it will overflow
            exp_term = CMPLX(HUGE(0.0_real64), HUGE(0.0_real64), kind=real64)
         ELSEIF (exp_arg_re < -LOG(HUGE(0.0_real64))) THEN
             ! Construct 0 if it will underflow
             exp_term = CMPLX(0.0_real64, 0.0_real64, kind=real64)
         ELSE
            exp_term = 2.0_real64 * EXP(CMPLX(exp_arg_re, 2.0_real64*xs*y, kind=real64))
         END IF

         IF (.NOT. (ieee_is_finite(REAL(exp_term)) .AND. ieee_is_finite(AIMAG(exp_term)))) THEN
            ret = exp_term
         ELSE
            ret = exp_term - ret
         END IF
      END IF
      RETURN
    END IF

    ! Algorithm 916 for smaller |z|
    IF (x < 10.0_real64) THEN
        prod2ax = 1.0_real64
        prodm2ax = 1.0_real64
        IF (ieee_is_nan(y)) THEN
            ret = CMPLX(HUGE(0.0_real64)/HUGE(0.0_real64), HUGE(0.0_real64)/HUGE(0.0_real64), kind=real64) ! NaN
            RETURN
        END IF

        IF (relerr == EPSILON(0.0_real64)) THEN
            IF (x < 5.0e-4_real64) THEN
                expx2 = 1.0_real64 - x*x * (1.0_real64 - 0.5_real64*x*x) ! Taylor for exp(-x^2)
                exp2ax = 1.0_real64 + (2.0_real64*a*x) * (1.0_real64 + (2.0_real64*a*x) * (0.5_real64 + 0.16666666666666666667_real64*(2.0_real64*a*x))) ! Taylor for exp(2ax)
                expm2ax = 1.0_real64 - (2.0_real64*a*x) * (1.0_real64 - (2.0_real64*a*x) * (0.5_real64 - 0.16666666666666666667_real64*(2.0_real64*a*x))) ! Taylor for exp(-2ax)
                DO n = 1, SIZE(expa2n2)
                    IF (expa2n2(n) == 0.0_real64) EXIT ! Underflowed in table
                    coef = expa2n2(n) * expx2 / (a2*REAL(n*n) + y*y)
                    prod2ax = prod2ax * exp2ax
                    prodm2ax = prodm2ax * expm2ax
                    sum1 = sum1 + coef
                    sum2 = sum2 + coef * prodm2ax
                    sum3 = sum3 + coef * prod2ax
                    sum5 = sum5 + coef * (2.0_real64*a) * n * sinh_taylor((2.0_real64*a)*n*x) ! Really sum5-sum4
                    !v = coef * (2.0_real64*a) * n * sinh_taylor((2.0_real64*a)*n*x)
                    ! Kahan add to sum5
                    !yk = v - sum5_c
                    !t  = sum5 + yk
                    !sum5_c = (t - sum5) - yk
                    !sum5 = t
                    IF (coef * prod2ax < relerr * sum3) EXIT
                END DO
            ELSE
                expx2 = EXP(-x*x)
                exp2ax = EXP((2.0_real64*a)*x)
                expm2ax = 1.0_real64 / exp2ax
                DO n = 1, SIZE(expa2n2)
                     IF (expa2n2(n) == 0.0_real64) EXIT ! Underflowed in table
                    coef = expa2n2(n) * expx2 / (a2*REAL(n*n) + y*y)
                    prod2ax = prod2ax * exp2ax
                    prodm2ax = prodm2ax * expm2ax
                    sum1 = sum1 + coef
                    sum2 = sum2 + coef * prodm2ax
                    sum4 = sum4 + (coef * prodm2ax) * (a*REAL(n))
                    sum3 = sum3 + coef * prod2ax
                    sum5 = sum5 + (coef * prod2ax) * (a*REAL(n))
                    !v = (coef * prodm2ax) * (a*REAL(n))
                    ! Kahan add to sum4
                    !yk = v - sum4_c
                    !t  = sum4 + yk
                    !sum4_c = (t - sum4) - yk
                    !sum4 = t

                    !v = (coef * prod2ax) * (a*REAL(n))
                    ! Kahan add to sum5
                    !yk = v - sum5_c
                    !t  = sum5 + yk
                    !sum5_c = (t - sum5) - yk
                    !sum5 = t
                    IF ((coef * prod2ax) * (a*REAL(n)) < relerr * sum5) EXIT
                END DO
            END IF
        ELSE ! relerr > epsilon, calculate exp(-a2*n*n) on the fly
             expx2 = EXP(-x*x)
             exp2ax = EXP((2.0_real64*a)*x)
             expm2ax = 1.0_real64 / exp2ax
             IF (x < 5.0e-4_real64) THEN
                expx2 = 1.0_real64 - x*x * (1.0_real64 - 0.5_real64*x*x)
                 DO n = 1, HUGE(0)
                    coef = EXP(-a2*REAL(n*n)) * expx2 / (a2*REAL(n*n) + y*y)
                    prod2ax = prod2ax * exp2ax
                    prodm2ax = prodm2ax * expm2ax
                    sum1 = sum1 + coef
                    sum2 = sum2 + coef * prodm2ax
                    sum3 = sum3 + coef * prod2ax
                    sum5 = sum5 + coef * (2.0_real64*a) * n * sinh_taylor((2.0_real64*a)*n*x) ! Really sum5-sum4
                    !v = coef * (2.0_real64*a) * n * sinh_taylor((2.0_real64*a)*n*x)
                    ! Kahan add to sum5
                    !yk = v - sum5_c
                    !t  = sum5 + yk
                    !sum5_c = (t - sum5) - yk
                    !sum5 = t
                    IF (coef * prod2ax < relerr * sum3) EXIT
                 END DO
             ELSE
                 DO n = 1, HUGE(0)
                    coef = EXP(-a2*REAL(n*n)) * expx2 / (a2*REAL(n*n) + y*y)
                    prod2ax = prod2ax * exp2ax
                    prodm2ax = prodm2ax * expm2ax
                    sum1 = sum1 + coef
                    sum2 = sum2 + coef * prodm2ax
                    sum4 = sum4 + (coef * prodm2ax) * (a*REAL(n))
                    sum3 = sum3 + coef * prod2ax
                    sum5 = sum5 + (coef * prod2ax) * (a*REAL(n))
                    !v = (coef * prod2ax) * (a*REAL(n))
                    ! Kahan add to sum5
                    !yk = v - sum5_c
                    !t  = sum5 + yk
                    !sum5_c = (t - sum5) - yk
                    !sum5 = t
                    IF ((coef * prod2ax) * (a*REAL(n)) < relerr * sum5) EXIT
                 END DO
             END IF
        END IF

        IF (y > -6.0_real64) THEN
            expx2erfcxy = expx2 * erfcx_real(y)
        ELSE
            expx2erfcxy = 2.0_real64 * EXP(y*y - x*x)
        END IF

        IF (y > 5.0_real64) THEN
            ! Large y: use x (abs(real(z))) as in original algorithm
            sinxy = SIN(x*y)
            ! partial ret (only real part significant here)
            ret = CMPLX( (expx2erfcxy - c*y*sum1) * COS(2.0_real64*x*y) + &
                         (c*x*expx2) * sinxy * sinc(x*y, sinxy), &
                         0.0_real64, kind=real64 )
        ELSE
          xs = REAL(z, kind=real64)
          sinxy = SIN(xs*y)
          sin2xy = SIN(2.0_real64*xs*y)
          cos2xy = COS(2.0_real64*xs*y)

          coef1 = expx2erfcxy - c*y*sum1
          coef2 = c * xs * expx2

          ret = CMPLX( coef1 * cos2xy + coef2 * sinxy * sinc(xs*y, sinxy), &
                       coef2 * sinc(2.0_real64*xs*y, sin2xy) - coef1 * sin2xy, kind=real64 )
        END IF

        ! Now add the remaining contributions (matches the C++ copysign logic)
        ret = ret + CMPLX( (0.5_real64*c)*y*(sum2 + sum3), &
                           (0.5_real64*c)*SIGN(ABS(sum5 - sum4), REAL(z, kind=real64)), kind=real64 )


    ELSE ! x >= 10 (Large x: only sum3 & sum5 contribute significantly)
        IF (ieee_is_nan(x) .OR. ieee_is_nan(y)) THEN
            ret = CMPLX(HUGE(0.0_real64)/HUGE(0.0_real64), HUGE(0.0_real64)/HUGE(0.0_real64), kind=real64) ! NaN
            RETURN
        END IF

        ret = CMPLX(EXP(-x*x), 0.0_real64, kind=real64) ! Initial term

        n0 = FLOOR(x/a + 0.5_real64) ! Start summation near peak
        IF (n0 < 1.0_real64) n0 = 1.0_real64 ! Ensure n0 >= 1
        dx = a*n0 - x
        sum3 = EXP(-dx*dx) / (a2*n0*n0 + y*y)
        sum5 = a*n0*sum3
        exp1 = EXP(4.0_real64*a*dx)
        exp1dn = 1.0_real64

        ! Loop downwards from n0-1 and upwards from n0+1
        dn_loop: DO dn = 1, HUGE(0)
            np = n0 + dn
            nm = n0 - dn
            IF (nm <= 0.0_real64) EXIT dn_loop ! Stop downward loop when n <= 0

            tp = EXP(-(a*REAL(dn)+dx)**2)
            exp1dn = exp1dn * exp1
            tm = tp * exp1dn
            tp = tp / (a2*np*np + y*y)
            tm = tm / (a2*nm*nm + y*y)
            sum3 = sum3 + tp + tm
            sum5 = sum5 + a * (np * tp + nm * tm)
            !v = a * (np * tp + nm * tm)  ! or v = a * np * tp
            !yk = v - sum5_c
            !t  = sum5 + yk
            !sum5_c = (t - sum5) - yk
            !sum5 = t
            IF (a * (np * tp + nm * tm) < relerr * sum5) GOTO 100 ! Convergence check
        END DO dn_loop

        ! Continue upwards loop only (since n0-dn became <= 0)
        up_loop: DO
            np = n0 + dn
            tp = EXP(-(a*REAL(dn)+dx)**2) / (a2*np*np + y*y)
            sum3 = sum3 + tp
            sum5 = sum5 + a * np * tp
            !v = a * np * tp
            !yk = v - sum5_c
            !t  = sum5 + yk
            !sum5_c = (t - sum5) - yk
            !sum5 = t
            IF (a * np * tp < relerr * sum5) GOTO 100 ! Convergence check
            dn = dn + 1
            IF (dn > 100000) GOTO 100 ! Safety break for infinite loop potential
        END DO up_loop

    END IF

    100 CONTINUE ! Label for exiting loops upon convergence

    !IF (AIMAG(z) < 0.0_real64) THEN
    !  ret = 2.0_real64 * EXP(-z*z) - CONJG(ret)
    !END IF

    !ret = ret + CMPLX( (0.5_real64*c)*y*(sum2 + sum3), &
    !                    (0.5_real64*c)*SIGN(sum5 - sum4, REAL(z, kind=real64)), kind=real64 )
  END FUNCTION Faddeeva_w


