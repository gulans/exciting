  !> @brief Helper function to compute erfcx(x) for real x.
  PURE FUNCTION erfcx_real(x_in) RESULT(res)
      REAL(real64), INTENT(IN) :: x_in
      REAL(real64) :: res
      IF (x_in >= 0.0_real64) THEN
          IF (x_in > 50.0_real64) THEN
              IF (x_in > 5.0e7_real64) THEN
                  res = ISPI / x_in
              ELSE
                  res = ISPI*((x_in*x_in) * (x_in*x_in+4.5_real64) + 2.0_real64) / &
                               (x_in * ((x_in*x_in) * (x_in*x_in+5.0_real64) + 3.75_real64))
              END IF
          ELSE
               res = erfcx_helper(400.0_real64 / (4.0_real64 + x_in))
          END IF
      ELSE
          IF (x_in < -26.7_real64) THEN
              res = HUGE(0.0_real64)
          ELSE IF (x_in < -6.1_real64) THEN
              res = 2.0_real64 * EXP(x_in*x_in)
          ELSE
              res = 2.0_real64 * EXP(x_in*x_in) - erfcx_helper(400.0_real64/(4.0_real64 - x_in))
          END IF
      END IF
  END FUNCTION erfcx_real

